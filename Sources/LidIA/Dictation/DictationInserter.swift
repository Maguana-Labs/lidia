/// Everything on a pasteboard, so it can be put back after a paste.
struct PasteboardSnapshot: Sendable, Equatable {
    struct Item: Sendable, Equatable {
        var representations: [(type: String, data: Data)]

        static func == (lhs: Item, rhs: Item) -> Bool {
            lhs.representations.map(\.type) == rhs.representations.map(\.type)
                && lhs.representations.map(\.data) == rhs.representations.map(\.data)
        }
    }

    var items: [Item]

    @MainActor
    static func capture(_ pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            Item(representations: item.types.compactMap { type in
                item.data(forType: type).map { (type.rawValue, $0) }
            })
        }
        return PasteboardSnapshot(items: items)
    }

    @MainActor
    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        let restored = items.map { item -> NSPasteboardItem in
            let pbItem = NSPasteboardItem()
            for representation in item.representations {
                pbItem.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
            }
            return pbItem
        }
        pasteboard.writeObjects(restored)
    }
}

/// Puts text on the pasteboard, runs `paste`, then restores what was there
/// before, unless something else (the user, a clipboard manager) has written
/// to the pasteboard in the meantime.
@MainActor
struct PasteboardTransaction {
    /// Marks our temporary contents so clipboard managers skip them
    /// (nspasteboard.org conventions).
    static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.source"),
    ]

    let pasteboard: NSPasteboard
    /// How long the target app gets to read the pasteboard before it is restored.
    var restoreDelay: Duration = .milliseconds(350)

    /// - Returns: whether the previous contents were restored.
    @discardableResult
    func perform(text: String, paste: () -> Void) async -> Bool {
        let snapshot = PasteboardSnapshot.capture(pasteboard)
        pasteboard.clearContents()
        pasteboard.declareTypes([.string] + Self.transientTypes, owner: nil)
        pasteboard.setString(text, forType: .string)
        for type in Self.transientTypes {
            pasteboard.setString(type.rawValue.hasSuffix("source") ? "io.lidia.app" : "", forType: type)
        }
        let ours = pasteboard.changeCount
        paste()
        try? await Task.sleep(for: restoreDelay)
        guard pasteboard.changeCount == ours else { return false }
        snapshot.restore(to: pasteboard)
        return true
    }
}

/// Inserts dictated text at the cursor of the frontmost app.
@MainActor
final class DictationInserter {
    private static let logger = Logger(subsystem: "io.lidia.app", category: "DictationInserter")
    /// Tags events we post so our own key monitor ignores them.
    nonisolated static let syntheticEventTag: Int64 = 0x4C_49_44_49  // "LIDI"

    enum Outcome: Equatable, Sendable {
        case accessibility
        case pasted
        /// A password field has secure input on; nothing was typed.
        case secureInput
        case failed(String)

        var inserted: Bool { self == .accessibility || self == .pasted }
    }

    var pasteboard: NSPasteboard = .general

    func insert(_ text: String, method: DictationInsertionMethod) async -> Outcome {
        guard !text.isEmpty else { return .failed("Nothing to insert") }
        if IsSecureEventInputEnabled() {
            return .secureInput
        }
        switch method {
        case .accessibility:
            return Self.insertViaAccessibility(text) ? .accessibility : .failed("This app doesn't accept text from Accessibility")
        case .automatic:
            if Self.insertViaAccessibility(text) { return .accessibility }
            return await paste(text)
        case .paste:
            return await paste(text)
        }
    }

    private func paste(_ text: String) async -> Outcome {
        await PasteboardTransaction(pasteboard: pasteboard).perform(text: text) {
            Self.postCommandV()
        }
        return .pasted
    }

    // MARK: - Accessibility

    /// Replaces the selection (or inserts at the caret) of the focused text
    /// element. Returns false, having changed nothing, when the element
    /// doesn't take text this way, so the caller can paste instead.
    static func insertViaAccessibility(_ text: String) -> Bool {
        guard AXIsProcessTrusted() else { return false }
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.3)
        var focusedRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
              let focusedRef, CFGetTypeID(focusedRef) == AXUIElementGetTypeID() else {
            return false
        }
        let element = focusedRef as! AXUIElement  // swiftlint:disable:this force_cast
        AXUIElementSetMessagingTimeout(element, 0.3)

        var settable = DarwinBoolean(false)
        guard AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success,
              settable.boolValue else { return false }
        // Without a readable value we can't tell whether the text went in, and
        // pasting on top of a silent success would type it twice.
        guard let before = stringValue(of: element) else { return false }
        guard AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success else {
            return false
        }
        guard let after = stringValue(of: element) else { return false }
        // Browsers and Electron apps often report success and do nothing.
        let changed = after != before
        if !changed { logger.info("Accessibility insert had no effect; falling back") }
        return changed
    }

    private static func stringValue(of element: AXUIElement) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success else { return nil }
        return value as? String
    }

    // MARK: - Keystrokes

    static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let keyCode = keyCodeForCharacter("v") ?? CGKeyCode(kVK_ANSI_V)
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: keyDown) else { continue }
            // Only ⌘: a dictation key still held mustn't turn this into ⌘⌥V.
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: syntheticEventTag)
            event.post(tap: .cghidEventTap)
        }
    }

    /// The key that types `character` in the current keyboard layout, so ⌘V
    /// is right on Dvorak or AZERTY too.
    static func keyCodeForCharacter(_ character: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let layoutPointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else {
            return nil
        }
        let layoutData = Unmanaged<CFData>.fromOpaque(layoutPointer).takeUnretainedValue() as Data
        let target = String(character)
        return layoutData.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in 0..<128 {
                var deadKeyState: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(
                    layout, UInt16(code), UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()),
                    OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeyState, chars.count, &length, &chars
                )
                if status == noErr, length > 0, String(utf16CodeUnits: chars, count: length) == target {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }
}
